import assert from 'node:assert/strict';
import fs from 'node:fs';
import {normalize,createSermon,createCard,merge,safePulpit} from '../src/domain.js';
let a=createSermon({title:'Mark: physician and bridegroom',passage:'Mark 2:13-22'});
let b=createSermon({title:'Colossians: sufficient in Christ',passage:'Col 2:6-23'});
const db=normalize({version:3,activeSermonId:b.id,sermons:[a,b]});
assert.equal(db.activeSermonId,b.id);
assert.equal(normalize(JSON.parse(JSON.stringify(db))).activeSermonId,b.id);
const older=normalize({version:1,sermons:[a]});
assert.equal(older.activeSermonId,'');
assert.equal(merge(db,older).activeSermonId,b.id);
const ocr=createCard({kind:'Observation',body:'Handwriting might contain OCR mistakes',verse:'Mark 2:17',location:'NOTE/my.note | page 2 | 10 ink element(s)',status:'To verify'});
assert.equal(ocr.status,'To verify');
const quote=createCard({kind:'Exact quotation',body:'Unverified captured quote',disposition:'Pulpit',status:'To verify',source:'Commentary',page:'15'});
a.cards=[ocr,quote];
assert.equal(safePulpit(a).length,0);
let sdk=fs.readFileSync('src/sdk.js','utf8'),app=fs.readFileSync('App.js','utf8');
for(const x of ['getLastSelectedText','getLassoText','getLassoElements','getPageDisplaySize','recognizeElements','setLassoBoxState(2)','FILE:READ'])assert(sdk.includes(x),x);
for(const x of ['CHANGE DESTINATION SERMON','RETURN TO NOTE','minHeight:44','captureStatus','To verify','screen===\'select\''])assert(app.includes(x),x);
console.log('PASS: source, OCR capture safety, active sermon persistence, privacy, and Manta navigation checks');
