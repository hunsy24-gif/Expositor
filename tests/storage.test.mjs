import assert from 'node:assert/strict';
import {createSermon,normalize} from '../src/domain.js';
import {dossierStore,KEYS} from '../src/storage-core.js';
function mock(){let data=new Map(),rejectKey=null,mutateRead=false;return {data,set rejectKey(k){rejectKey=k},set mutateRead(x){mutateRead=x},async getItem(k){const v=data.get(k)??null;return mutateRead&&k===KEYS.main&&v?v+'!':v},async setItem(k,v){if(k===rejectKey)throw Error('Injected disk write failure');data.set(k,v)}}}
let a=mock(),store=dossierStore(a),s=createSermon({title:'Mark 2',passage:'Mark 2:13-22'});
await store.store(normalize({version:3,sermons:[s]}));
assert.equal((await store.load()).sermons[0].title,'Mark 2');
const v=a.data.get(KEYS.main);
await store.store({version:3,sermons:[s]});
assert.equal(a.data.get(KEYS.previous),v);
a.data.set(KEYS.main,'{broken');
let recovered=await store.load();
assert.equal(recovered.recoveredFromPrevious,true);
assert.equal(recovered.sermons.length,1);
await store.store({version:3,sermons:[s]});
assert.equal(a.data.get(KEYS.previous),v,'previous good copy must survive damaged primary');
a.rejectKey=KEYS.previous;
await assert.rejects(store.store({version:3,sermons:[s]}));
a.rejectKey=null;
a.data.set(KEYS.main,v);
a.rejectKey=KEYS.main;
await assert.rejects(store.store({version:3,sermons:[s]}));
a.rejectKey=null;
a.data.set(KEYS.main,JSON.stringify({version:99,sermons:[]}));
await assert.rejects(store.store({version:3,sermons:[s]}),/newer Expositor/);
await assert.rejects(store.load(),/newer Expositor/);
const blank=mock(),bs=dossierStore(blank);assert.equal((await bs.load()).sermons.length,0);
blank.data.set(KEYS.legacy,v);assert.equal((await bs.load()).sermons.length,1);
const corrupt=mock(),cs=dossierStore(corrupt);corrupt.data.set(KEYS.main,'{bad');
await assert.rejects(cs.load());
console.log('PASS: storage integrity, recovery, corruption protection, migration, read-back and write-failure tests');
